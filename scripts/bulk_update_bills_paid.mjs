async function runBulkUpdate() {
  const BATCH_SIZE = 100;
  let totalFound = 0;
  let totalUpdated = 0;
  const notFoundBills = [];

  for (let i = 0; i < billNumbers.length; i += BATCH_SIZE) {
    const batch = billNumbers.slice(i, i + BATCH_SIZE);
    
    // 1. Fetch matching bills
    const { data: bills, error: fetchErr } = await supabase
      .from('bills')
      .select('*')
      .in('bill_no', batch);

    if (fetchErr) {
      console.error(`Error fetching batch ${i}:`, fetchErr);
      continue;
    }

    if (!bills || bills.length === 0) {
      console.warn(`No bills found for batch starting at ${i}`);
      notFoundBills.push(...batch);
      continue;
    }

    totalFound += bills.length;
    const foundSet = new Set(bills.map(b => b.bill_no.toUpperCase()));
    for (const bNo of batch) {
      if (!foundSet.has(bNo.toUpperCase())) {
        notFoundBills.push(bNo);
      }
    }

    // 2. Prepare updates for each bill
    const updates = bills.map(b => {
      const netAmt = Number(b.bill_net_amt) || 0;
      const history = Array.isArray(b.edit_history) ? [...b.edit_history] : [];
      history.push({
        seq: history.length + 1,
        date: '09/08/2026',
        time: new Date().toTimeString().slice(0, 5),
        by: 'PRATIXA',
        role: 'user',
        action: 'PAID (FBR -> Cash)',
        mode: 'Cash',
        amount: netAmt,
        changes: 'Bulk FBR to Cash Paid update'
      });

      return {
        id: b.id,
        bill_no: b.bill_no,
        date: b.date,
        salesperson_name: b.salesperson_name,
        party_name: b.party_name,
        party_code: b.party_code,
        beat_name: b.beat_name,
        bill_net_amt: netAmt,
        collected_amount: netAmt,
        cash_amount: netAmt,
        upi_amount: 0,
        cheque_amount: 0,
        outstanding_amount: 0,
        line_cut_amt: 0,
        payment_mode: 'Cash',
        payment_method: 'Cash',
        payment_date: '09/08/2026',
        payment_time: b.payment_time || new Date().toTimeString().slice(0, 5),
        user: 'PRATIXA',
        edit_date: '09/08/2026',
        discrepancy_reason: null,
        cancel_line: null,
        edit_history: history,
        updated_at: new Date().toISOString()
      };
    });

    // 3. Upsert back to Supabase
    const { error: updateErr } = await supabase
      .from('bills')
      .upsert(updates, { onConflict: 'id' });

    if (updateErr) {
      console.error(`Error updating batch starting at ${i}:`, updateErr);
    } else {
      totalUpdated += updates.length;
      console.log(`Updated ${totalUpdated} / ${billNumbers.length} bills...`);
    }
  }

  console.log('----------------------------------------------------');
  console.log(`FINISHED! Total requested: ${billNumbers.length}`);
  console.log(`Total found in Supabase: ${totalFound}`);
  console.log(`Total successfully updated to PAID / Cash / 09/08/2026 / PRATIXA: ${totalUpdated}`);
  if (notFoundBills.length > 0) {
    console.log(`Bills not found in database (${notFoundBills.length}):`, notFoundBills.join(', '));
  }
}

