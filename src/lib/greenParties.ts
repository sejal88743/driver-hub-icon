let cachedGreenParties: GreenParty[] | null = null;
let cachedCodeSet: Set<string> | null = null;
let cachedNameSet: Set<string> | null = null;
let cachedMap: Map<string, string> | null = null;

function normalizeCode(c?: string): string {
  if (!c) return '';
  return String(c).trim().toUpperCase().replace(/[^A-Z0-9]/g, '');
}

function normalizeName(n?: string): string {
  if (!n) return '';
  return String(n).trim().toUpperCase().replace(/[^A-Z0-9]/g, '');
}

export function getGreenParties(): GreenParty[] {
  if (cachedGreenParties) return cachedGreenParties;

  // Try localStorage
  if (typeof window !== 'undefined') {
    try {
      const stored = localStorage.getItem('vt_green_parties');
      if (stored) {
        const parsed = JSON.parse(stored);
        if (Array.isArray(parsed) && parsed.length > 0) {
          cachedGreenParties = parsed;
          buildCaches();
          return cachedGreenParties!;
        }
      }
    } catch {
      /* ignore */
    }
  }

  cachedGreenParties = INITIAL_GREEN_PARTIES;
  buildCaches();
  return cachedGreenParties;
}

function buildCaches() {
  const parties = cachedGreenParties || INITIAL_GREEN_PARTIES;
  cachedCodeSet = new Set<string>();
  cachedNameSet = new Set<string>();
  cachedMap = new Map<string, string>();

  parties.forEach(p => {
    const normCode = normalizeCode(p.partyCode);
    const normName = normalizeName(p.partyName);
    if (normCode) {
      cachedCodeSet!.add(normCode);
      cachedMap!.set(normCode, p.partyName);
    }
    if (normName) {
      cachedNameSet!.add(normName);
    }
  });
}

export function loadGreenPartiesFromSettings(settings: Record<string, string>) {
  if (settings && settings['green_party_list']) {
    try {
      const parsed = JSON.parse(settings['green_party_list']);
      if (Array.isArray(parsed) && parsed.length > 0) {
        cachedGreenParties = parsed;
        buildCaches();
        if (typeof window !== 'undefined') {
          localStorage.setItem('vt_green_parties', JSON.stringify(parsed));
        }
      }
    } catch {
      /* ignore */
    }
  }
}

export function saveGreenParties(list: GreenParty[]): void {
  cachedGreenParties = list;
  buildCaches();
  if (typeof window !== 'undefined') {
    try {
      localStorage.setItem('vt_green_parties', JSON.stringify(list));
    } catch {
      /* ignore */
    }
  }
}

export function isGreenParty(partyCode?: string, partyName?: string): boolean {
  if (!cachedCodeSet) getGreenParties();

  const c = normalizeCode(partyCode);
  if (c && cachedCodeSet?.has(c)) return true;

  const n = normalizeName(partyName);
  if (n && cachedNameSet?.has(n)) return true;

  return false;
}

export function getGreenPartyNameByCode(partyCode?: string): string | null {
  if (!cachedMap) getGreenParties();
  const c = normalizeCode(partyCode);
  if (c && cachedMap?.has(c)) {
    return cachedMap.get(c)!;
  }
  return null;
}

export function addGreenParty(partyCode: string, partyName: string): GreenParty[] {
  const current = getGreenParties();
  const code = partyCode.trim().toUpperCase();
  const name = partyName.trim().toUpperCase();
  const filtered = current.filter(p => p.partyCode.trim().toUpperCase() !== code);
  const updated = [{ partyCode: code, partyName: name }, ...filtered];
  saveGreenParties(updated);
  return updated;
}

export function removeGreenParty(partyCode: string): GreenParty[] {
  const current = getGreenParties();
  const code = partyCode.trim().toUpperCase();
  const updated = current.filter(p => p.partyCode.trim().toUpperCase() !== code);
  saveGreenParties(updated);
  return updated;
}
